#!/usr/bin/env bash
# Install Deutschheft as an offline desktop app on Linux: builds ./app and adds a launcher that opens it in its own
# window (Chrome/Chromium/Edge app mode) at http://127.0.0.1:47613. Run again after changing the sources.
# Remove the launcher with: ./install_app.sh --uninstall
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
DESKTOP="$DATA/applications/deutschheft.desktop"
ICONS="$DATA/icons/hicolor"
LAUNCHER="$DIR/deutschheft.sh"
URL="http://127.0.0.1:47613/index.html"

if [ "${1:-}" = "--uninstall" ]; then
  rm -f "$DESKTOP" "$LAUNCHER" "$ICONS/512x512/apps/deutschheft.png" "$ICONS/192x192/apps/deutschheft.png"
  echo "Removed the Deutschheft launcher. Your progress stays in the browser profile (and in your save file, if you chose one)."
  exit 0
fi

python3 "$DIR/build_app.py"

BROWSER="$(command -v google-chrome || command -v google-chrome-stable || command -v chromium || command -v chromium-browser || command -v microsoft-edge || true)"
if [ -z "$BROWSER" ]; then
  echo "Deutschheft needs Chrome, Chromium or Edge for its app window and save file." >&2
  exit 1
fi

# The launcher starts the short-lived local server, then opens the app window.
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by install_app.sh: open Deutschheft in its own window.
python3 "$DIR/serve_app.py" --daemon || true
exec "$BROWSER" --app="$URL" "\$@"
EOF
chmod +x "$LAUNCHER"

mkdir -p "$DATA/applications" "$ICONS/512x512/apps" "$ICONS/192x192/apps"
cp "$DIR/app/icons/icon-512.png" "$ICONS/512x512/apps/deutschheft.png"
cp "$DIR/app/icons/icon-192.png" "$ICONS/192x192/apps/deutschheft.png"
cat > "$DESKTOP" <<EOF
[Desktop Entry]
Type=Application
Name=Deutschheft
GenericName=German practice
Comment=A1 German with explained grammar and spaced repetition
Exec="$LAUNCHER"
Icon=deutschheft
Terminal=false
Categories=Education;Languages;
StartupWMClass=127.0.0.1__index.html
EOF
chmod +x "$DESKTOP"
if command -v update-desktop-database >/dev/null; then update-desktop-database "$DATA/applications" >/dev/null 2>&1 || true; fi
if command -v gtk-update-icon-cache >/dev/null; then gtk-update-icon-cache -q "$ICONS" >/dev/null 2>&1 || true; fi

echo "Installed. Open Deutschheft from your app launcher, or run: $LAUNCHER"
